"""Human-readable renderings of TaskSeam state."""

SHORT_ID = 7
SECTIONS = (
    ("decision", "Accepted decisions"),
    ("constraint", "Active constraints"),
    ("question", "Open questions"),
)
AGENTS_MD_START = "<!-- taskseam:start -->"
AGENTS_MD_END = "<!-- taskseam:end -->"


def short(item_id):
    return item_id[:SHORT_ID]


def _line(item):
    body = " ".join(item["body"].split())
    return "- {} `{}` _({})_".format(body, short(item["id"]), item.get("source") or "unknown")


def brief(task, items, budget=None, header=True, ids=True):
    """Render current state as Markdown.

    ``budget`` caps the output in characters. Items that do not fit are never
    dropped silently: the brief ends with an explicit omission count per kind.
    """
    lines = []
    if header:
        lines.append("# TaskSeam: " + task["title"])
        lines.append("")
    if not items:
        lines.append("No accepted decisions, constraints, or open questions are recorded yet.")
        return "\n".join(lines) + "\n"
    footer = ("Recorded project state with its source in parentheses; check it against the code "
              "before relying on it. IDs accept unique prefixes; `taskseam explain <id>` shows evidence.")
    omitted = {}
    used = sum(len(line) + 1 for line in lines) + len(footer) + 200
    for kind, title in SECTIONS:
        group = [item for item in items if item["kind"] == kind]
        if not group:
            continue
        section = ["## {} ({})".format(title, len(group))]
        for item in group:
            text = _line(item) if ids else "- " + " ".join(item["body"].split())
            cost = len(text) + 1 + (len(section[0]) + 2 if len(section) == 1 else 0)
            if budget is not None and used + cost > budget:
                omitted[kind] = omitted.get(kind, 0) + 1
                continue
            used += cost
            section.append(text)
        if len(section) > 1:
            lines.extend(section)
            lines.append("")
    if omitted:
        parts = ["{} {}{}".format(count, kind, "s" if count != 1 else "")
                 for kind, count in omitted.items()]
        lines.append("**Omitted to fit the size budget:** " + ", ".join(parts) +
                     ". Call the `taskseam_context` tool or run `taskseam show` for everything.")
        lines.append("")
    if ids:
        lines.append("_" + footer + "_")
    return "\n".join(lines).rstrip() + "\n"


def splice_agents_md(existing, block):
    """Insert or replace the TaskSeam-managed block inside an AGENTS.md-style file."""
    managed = "{}\n<!-- Generated by `taskseam export`; edits inside this block are overwritten. -->\n{}{}\n".format(
        AGENTS_MD_START, block if block.endswith("\n") else block + "\n", AGENTS_MD_END)
    start, end = existing.find(AGENTS_MD_START), existing.find(AGENTS_MD_END)
    if start != -1 and end != -1 and end > start:
        tail = existing[end + len(AGENTS_MD_END):]
        return existing[:start] + managed.rstrip("\n") + tail if tail else existing[:start] + managed
    if start != -1 or end != -1:
        raise ValueError("Found only one TaskSeam marker; fix the file before exporting")
    if not existing:
        return managed
    return existing.rstrip("\n") + "\n\n" + managed
